"""Poses in the plane, (x, y, yaw): composing and inverting."""

import math


def compose(a, b):
    """a ∘ b: b expressed in a's frame, moved into a's parent."""
    c, s = math.cos(a[2]), math.sin(a[2])
    return (a[0] + c * b[0] - s * b[1], a[1] + s * b[0] + c * b[1], a[2] + b[2])


def inverse(a):
    c, s = math.cos(a[2]), math.sin(a[2])
    return (-c * a[0] - s * a[1], s * a[0] - c * a[1], -a[2])
