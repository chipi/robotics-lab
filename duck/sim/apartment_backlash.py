"""Write scene_apartment_backlash.xml: Pollen's apartment with the robot that has backlash.

velstand was trained on the robot with backlash and does not step on the one without it, which is
what upstream's apartment scene carries (RFC-0002 §3.5). This builds the variant from upstream's
own files, so it follows them: scene_backlash.xml (its keyframes match the backlash robot's joints)
with the full-collision backlash robot and the apartment instead of the ground-contact robot and the
floor plane.

The file goes next to upstream's scenes, because the robot's meshdir is relative to the scene file.
It is an untracked file in the microduck_rl checkout; offer it upstream rather than forking.

    python duck/sim/apartment_backlash.py [/work/pollen/microduck_rl]
    DUCK_SIM_SCENE=apartment_backlash scripts/duck-sim     # in the microduck checkout
"""

import re
import sys
from pathlib import Path

rl = Path(sys.argv[1] if len(sys.argv) > 1 else "/work/pollen/microduck_rl")
scenes = rl / "src" / "mjlab_microduck" / "robot" / "microduck"
source = (scenes / "scene_backlash.xml").read_text()

include = '<include file="robot_groundcontact_backlash.xml" />'
floor = re.compile(r'\s*<geom name="floor"[^>]*/>')
if source.count(include) != 1 or len(floor.findall(source)) != 1:
    raise SystemExit("scene_backlash.xml changed shape upstream; update this script")
for name in ("robot_allcollisions_backlash.xml", "apartment.xml"):
    if not (scenes / name).exists():
        raise SystemExit(f"{name} missing upstream")

scene = source.replace(include, '<include file="robot_allcollisions_backlash.xml" />\n'
                                 '    <include file="apartment.xml" />')
scene = floor.sub("\n        <!-- no floor plane: the apartment lays its own floors -->", scene)
out = scenes / "scene_apartment_backlash.xml"
out.write_text("<!-- Generated by robotics-lab duck/sim/apartment_backlash.py; do not edit. -->\n" + scene)
print(f"wrote {out}")
